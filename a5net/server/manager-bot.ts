function normalize(value: string): string {
  return value
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9@._-]+/gi, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function stem(value: string): string {
  let word = value
  for (const suffix of STEM_SUFFIXES) {
    if (word.length - suffix.length >= 4 && word.endsWith(suffix)) {
      word = word.slice(0, -suffix.length)
      break
    }
  }
  return word
}

function tokenStems(normalized: string): Set<string> {
  const result = new Set<string>()
  for (const token of normalized.split(' ')) {
    if (token.length < 2 || STOP_WORDS.has(token)) continue
    result.add(stem(token))
  }
  return result
}

function hasPrefix(stems: Set<string>, value: string): boolean {
  if (value.length < 4) return false
  const head = value.slice(0, 4)
  for (const item of stems) {
    if (item.length >= 4 && (item.startsWith(head) || value.startsWith(item.slice(0, 4)))) return true
  }
  return false
}

function scoreTopic(normalized: string, rawTokens: Set<string>, stems: Set<string>, topic: Topic): number {
  let score = 0
  for (const keyword of topic.keywords) {
    const normalizedKeyword = normalize(keyword)
    if (!normalizedKeyword) continue
    if (normalizedKeyword.includes(' ')) {
      const words = normalizedKeyword.split(' ')
      const matched = words.every(word => rawTokens.has(word) || stems.has(stem(word)))
      if (matched) score += 4 + words.length
      continue
    }
    const keywordStem = stem(normalizedKeyword)
    if (stems.has(keywordStem)) score += 2.5
    else if (hasPrefix(stems, keywordStem)) score += 1.8
    else if (normalizedKeyword.length >= 5 && normalized.includes(normalizedKeyword)) score += 1
  }
  return score * (topic.weight ?? 1)
}

function findTopic(id: string): Topic {
  return TOPICS.find(topic => topic.id === id) ?? TOPICS[0]!
}

function contactLine(): string {
  return OWNER_CONTACT_URL ? `\n\nНаписать A5000: ${OWNER_CONTACT_URL}` : ''
}

function replyFor(topic: Topic, extra = ''): ManagerReply {
  const text = extra ? `${extra}\n\n${topic.answer}` : topic.answer
  const withContact = topic.escalate ? `${text}${contactLine()}` : text
  return {
    text: withContact,
    intent: topic.id,
    suggestions: topic.suggestions.slice(0, 4),
    escalate: Boolean(topic.escalate),
    createdAt: new Date().toISOString(),
  }
}

function looksLikeQuestion(raw: string): boolean {
  return raw.includes('?') || QUESTION_RE.test(normalize(raw))
}

function lastBotIntent(history: ManagerMessageView[]): string {
  for (let index = history.length - 1; index >= 0; index -= 1) {
    const message = history[index]
    if (!message) continue
    if (message.role === 'bot' && message.intent) return message.intent
  }
  return ''
}

export function answerManagerMessage(input: {
  text: string
  history: ManagerMessageView[]
}): ManagerReply {
  const raw = input.text.trim().slice(0, 2000)
  const normalized = normalize(raw)

  if (!normalized || normalized.length < 2) {
    return replyFor({
      id: 'filter',
      label: 'пустое сообщение',
      keywords: [],
      weight: 1,
      answer: 'Напишите вопрос по площадке: вход, инвайт, профиль, публикация, жалоба или ошибка. Я отвечу по делу.',
      suggestions: DEFAULT_SUGGESTIONS,
    })
  }

  const stems = tokenStems(normalized)
  const rawTokens = new Set(normalized.split(' '))
  const ranked = TOPICS
    .map(topic => ({ topic, score: scoreTopic(normalized, rawTokens, stems, topic) }))
    .sort((left, right) => right.score - left.score)
  const best = ranked[0]
  const second = ranked[1]
  const genericSecond = new Set(['vague', 'greeting', 'thanks', 'goodbye', 'help', 'about_bot', 'filter', 'unknown'])

  const isGreeting = /^(привет|здравствуйте|здравствуй|добрый день|добрый вечер|доброе утро|хай|ку)(\s|!|,|$)/.test(raw.toLowerCase())
  const isThanks = /^(спасибо|благодарю|спс|пасибо)(\s|!|,|$)/.test(raw.toLowerCase())
  const isGoodbye = /^(пока|до свидания|всего доброго|бай)(\s|!|,|$)/.test(raw.toLowerCase())

  if (isThanks && (!best || best.score < 2)) return replyFor(findTopic('thanks'))
  if (isGoodbye && (!best || best.score < 2)) return replyFor(findTopic('goodbye'))
  if (isGreeting && (!best || best.score < 2.2)) {
    return replyFor(findTopic('greeting'))
  }

  if (best && best.score >= 2.4) {
    const empathy = best.topic.empathy && EMPATHY_RE.test(normalized)
      ? 'Понимаю, это неприятно. Давайте разберёмся.'
      : ''
    let extra = empathy
    if (second && second.score >= 2.4 && second.score >= best.score * 0.8 && second.topic.id !== best.topic.id && !genericSecond.has(second.topic.id)) {
      extra = `${extra ? `${extra}\n\n` : ''}Если вопрос ещё и про «${second.topic.label}», уточните — отвечу отдельно.`
    }
    return replyFor(best.topic, extra)
  }

  if (best && best.score >= 1.2) {
    if (best.topic.id === 'vague') {
      const context = lastBotIntent(input.history)
      if (context && context !== 'vague' && context !== 'greeting') {
        return replyFor(findTopic('vague'), 'Похоже, мы уже начали разбираться. Уточните детали — и я дам следующий шаг.')
      }
      return replyFor(best.topic)
    }
    return replyFor(best.topic, 'Похоже, вопрос про это. Если я понял неверно — уточните.')
  }

  if (looksLikeQuestion(raw)) {
    if (!PLATFORM_HINT_RE.test(normalized)) {
      return replyFor({
        id: 'filter',
        label: 'не по теме',
        keywords: [],
        weight: 1,
        answer: 'Это не про A5NET. Я бот-помощник площадки и отвечаю только на вопросы про аккаунт, инвайты, профиль, публикации, комментарии, подписки, друзей, коллаборации, жалобы и ошибки. Сформулируйте вопрос по площадке — и я помогу.',
        suggestions: DEFAULT_SUGGESTIONS,
      })
    }
    return replyFor({
      id: 'unknown',
      label: 'нет ответа',
      keywords: [],
      weight: 1,
      escalate: true,
      answer: 'Точного ответа у меня нет — это не стандартный вопрос по площадке. Напишите A5000 в личные сообщения и приложите детали: что случилось, что уже пробовали и текст ошибки. А я могу помочь с входом, инвайтами, профилем, публикациями или жалобами.',
      suggestions: DEFAULT_SUGGESTIONS,
    })
  }

  return replyFor({
    id: 'filter',
    label: 'не по теме',
    keywords: [],
    weight: 1,
    answer: 'Я бот-помощник A5NET и отвечаю только на вопросы по площадке: вход и аккаунт, инвайты, профиль, публикации, комментарии, подписки, друзья, коллаборации, жалобы и ошибки. Сформулируйте вопрос по одному из этих разделов — и я помогу.',
    suggestions: DEFAULT_SUGGESTIONS,
  })
}

